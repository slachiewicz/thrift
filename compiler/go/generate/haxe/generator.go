// generator is t_haxe_generator for one program.
type generator struct {
	program *sema.Program
	opts    Options

	programName string
	serviceName string

	tmpCounter int
	level      int // indent_

	packageName string
	packageDir  string

	// fService is f_service_: the member ofstream generate_service_*
	// writes to without an explicit out parameter, exactly like the C++
	// class field.
	fService *strings.Builder
}

func newGenerator(program *sema.Program, opts Options) *generator {
	return &generator{program: program, opts: opts, programName: program.Name()}
}

// generate is t_generator::generate_program restricted to what
// t_haxe_generator overrides.
func (g *generator) generate() (err error) {
	defer func() {
		if r := recover(); r != nil {
			if e, ok := r.(*emit.Error); ok {
				err = e
				return
			}
			panic(r)
		}
	}()
	g.initGenerator()
	for _, e := range g.program.Enums() {
		g.generateEnum(e)
	}
	for _, t := range g.program.Typedefs() {
		g.generateTypedef(t)
	}
	for _, s := range g.program.Objects() {
		if s.IsXception() {
			g.generateXception(s)
		} else {
			g.generateStruct(s)
		}
	}
	g.generateConsts(g.program.Consts())
	for _, s := range g.program.Services() {
		g.serviceName = s.Name()
		g.generateService(s)
	}
	g.closeGenerator()
	return nil
}

func (g *generator) closeGenerator() {
	// Nothing in haxe.
}

// ---- indent-tracked writer ----

// indent is indent(): two spaces per level (t_generator::indent_str).
func (g *generator) indent() string {
	return strings.Repeat("  ", g.level)
}

func (g *generator) indentUp()   { g.level++ }
func (g *generator) indentDown() { g.level-- }

// line is `indent(out) << s << '\n'`.
func (g *generator) line(out *strings.Builder, s string) {
	out.WriteString(g.indent())
	out.WriteString(s)
	out.WriteString("\n")
}

// indentRaw is `indent(out) << s`, with no trailing newline, for call
// sites that keep writing to the same line afterwards.
func (g *generator) indentRaw(out *strings.Builder, s string) {
	out.WriteString(g.indent())
	out.WriteString(s)
}

// scopeUp is t_oop_generator::scope_up.
func (g *generator) scopeUp(out *strings.Builder) {
	g.line(out, "{")
	g.indentUp()
}

// scopeDown is t_oop_generator::scope_down.
func (g *generator) scopeDown(out *strings.Builder) {
	g.indentDown()
	g.line(out, "}")
}

// tmp is t_generator::tmp: a name with a running number appended.
func (g *generator) tmp(name string) string {
	s := name + strconv.Itoa(g.tmpCounter)
	g.tmpCounter++
	return s
}

// upcaseString is t_oop_generator::upcase_string.
func upcaseString(in string) string { return strings.ToUpper(in) }

func isUpper(c byte) bool { return c >= 'A' && c <= 'Z' }
func isLower(c byte) bool { return c >= 'a' && c <= 'z' }
func toUpperByte(c byte) byte {
	if isLower(c) {
		return c - 'a' + 'A'
	}
	return c
}
func toLowerByte(c byte) byte {
	if isUpper(c) {
		return c - 'A' + 'a'
	}
	return c
}

// formatDouble mimics `ostream << double` with the default precision of
// six significant digits, as used by render_const_value's TYPE_DOUBLE case
// (no setprecision call is in effect there).
func formatDouble(f float64) string {
	return strconv.FormatFloat(f, 'g', 6, 64)
}

// itoa32 formats a 32-bit signed integer, like `ostream << int32_t`.
func itoa32(v int32) string {
	return strconv.FormatInt(int64(v), 10)
}

