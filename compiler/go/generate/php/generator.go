// Generator is t_php_generator.
type Generator struct {
	program     *sema.Program
	opts        Options
	serviceName string
	indentLevel int
	tmpCounter  int

	packageDir string // package_dir_

	// fTypes is f_types_: the shared Types.php builder used only when
	// opts.Classmap is set. It is opened in initGenerator and written
	// once in closeGenerator.
	fTypes     strings.Builder
	fTypesName string

	// fService is f_service_: the shared per-service builder used only
	// when opts.Classmap is set. It is opened fresh in generateService
	// and written once at the end of generateService.
	fService     strings.Builder
	fServiceName string
}

// New is the t_php_generator constructor.
func New(program *sema.Program, opts Options) *Generator {
	return &Generator{program: program, opts: opts}
}

// Generate is t_generator::generate_program.
func (g *Generator) Generate() (err error) {
	defer func() {
		if r := recover(); r != nil {
			if e, ok := r.(*emit.Error); ok {
				err = e
				return
			}
			if e, ok := r.(*sema.Error); ok {
				err = e
				return
			}
			panic(r)
		}
	}()
	g.initGenerator()
	for _, e := range g.program.Enums() {
		g.generateEnum(e)
	}
	for _, t := range g.program.Typedefs() {
		g.generateTypedef(t)
	}
	for _, s := range g.program.Objects() {
		if s.IsXception() {
			g.generateXception(s)
		} else {
			g.generateStruct(s)
		}
	}
	g.generateConsts(g.program.Consts())
	for _, s := range g.program.Services() {
		g.serviceName = s.Name()
		g.generateService(s)
	}
	g.closeGenerator()
	return nil
}

// ---- t_generator and t_oop_generator helpers ----

func (g *Generator) indentUp()   { g.indentLevel++ }
func (g *Generator) indentDown() { g.indentLevel-- }

// indent is indent(): t_php_generator overrides indent_str() to four
// spaces (the base t_generator default is two).
func (g *Generator) indent() string {
	return strings.Repeat("    ", g.indentLevel)
}

func (g *Generator) scopeUp(out *strings.Builder) {
	out.WriteString(g.indent() + "{\n")
	g.indentUp()
}

func (g *Generator) scopeDown(out *strings.Builder) {
	g.indentDown()
	out.WriteString(g.indent() + "}\n")
}

func (g *Generator) tmp(name string) string {
	s := name + strconv.Itoa(g.tmpCounter)
	g.tmpCounter++
	return s
}

func (g *Generator) outDir() string {
	if g.program.IsOutPathAbsolute() {
		return g.program.OutPath() + "/"
	}
	return g.program.OutPath() + g.opts.OutDirBase() + "/"
}

func autogenSummary() string {
	return "Autogenerated by Thrift Compiler (" + version.Version + ")"
}

func autogenComment() string {
	return "/**\n" + " * " + autogenSummary() + "\n" + " *\n" +
		" * DO NOT EDIT UNLESS YOU ARE SURE THAT YOU KNOW WHAT YOU ARE DOING\n" +
		" *  @generated\n" + " */\n"
}

// phpAutogenComment is php_autogen_comment: it splices "phpcs:disable"
// lines into the closing of the standard autogen comment for the file
// shapes that contain the identifiers those sniffs would flag.
func phpAutogenComment(phpcsDisables []string) string {
	s := autogenComment()
	if len(phpcsDisables) == 0 {
		return s
	}
	closer := strings.LastIndex(s, " */")
	block := " *\n"
	for _, rule := range phpcsDisables {
		block += " * phpcs:disable " + rule + "\n"
	}
	return s[:closer] + block + s[closer:]
}

