// haxeThriftAddImport is t_haxe_generator::haxe_thrift_add_import. It uses
// ttyp (not its true type) for the program and name lookups, only the
// true type for the base-type skip check, exactly like the C++ code.
func (g *generator) haxeThriftAddImport(ttyp sema.Type, imports *strings.Builder, excludeShortName string) {
	trueType := sema.TrueType(ttyp)
	if trueType.IsBaseType() {
		return
	}
	program := ttyp.Program()
	if program != nil && program != g.program {
		pkg := makePackageName(program.Namespace("haxe"))
		if pkg != "" {
			shortName := g.makeHaxeUserTypeName(ttyp.Name())
			// Skip if the short name matches the entity being defined — the
			// local definition takes precedence and an import of a
			// same-named foreign type would shadow it (THRIFT-5320).
			if excludeShortName != "" && shortName == excludeShortName {
				return
			}
			// Skip if a same-named type is already imported — two imports
			// with the same short name produce an unresolvable ambiguity
			// in Haxe.
			if strings.Contains(imports.String(), "."+shortName+";\n") {
				return
			}
			if !strings.Contains(imports.String(), pkg+"."+ttyp.Name()) {
				imports.WriteString("import " + pkg + "." + shortName + ";\n")
			}
		}
	}
}

// haxeThriftGenImportsStruct is the t_struct overload of
// t_haxe_generator::haxe_thrift_gen_imports.
func (g *generator) haxeThriftGenImportsStruct(tstruct *sema.Struct, imports *strings.Builder, excludeShortName string) {
	for _, m := range tstruct.Members() {
		g.haxeThriftAddImport(m.Type(), imports, excludeShortName)
	}
}

// haxeThriftGenImportsServiceInto is the t_service overload of
// t_haxe_generator::haxe_thrift_gen_imports.
func (g *generator) haxeThriftGenImportsServiceInto(tservice *sema.Service, imports *strings.Builder) {
	// Exclude same-named foreign types to prevent them from shadowing the
	// local service definition.
	exclude := g.makeHaxeUserTypeName(tservice.Name())

	for _, f := range tservice.Functions() {
		g.haxeThriftAddImport(f.ReturnType(), imports, exclude)

		// args and exceptions structs
		g.haxeThriftGenImportsStruct(f.Arglist(), imports, exclude)
		g.haxeThriftGenImportsStruct(f.Xceptions(), imports, exclude)
	}

	// service implements / extends
	g.haxeThriftAddImport(tservice, imports, exclude)
	if tservice.Extends() != nil {
		g.haxeThriftGenImportsServiceInto(tservice.Extends(), imports)
	}
}

// haxeThriftGenImportsService is the string-returning t_service overload
// of t_haxe_generator::haxe_thrift_gen_imports.
func (g *generator) haxeThriftGenImportsService(tservice *sema.Service) string {
	var imports strings.Builder
	g.haxeThriftGenImportsServiceInto(tservice, &imports)
	return imports.String()
}

// typeCanBeNull is t_haxe_generator::type_can_be_null.
func typeCanBeNull(ttype sema.Type) bool {
	ttype = sema.TrueType(ttype)

	if ttype.IsContainer() || ttype.IsStruct() || ttype.IsXception() || ttype.IsString() {
		return true
	}

	if ttype.IsBaseType() {
		switch ttype.(*sema.BaseType).Base() {
		case sema.TypeString:
			// case sema.TypeI64: Int64 is not really nullable, even though
			// it behaved that way before Haxe 3.2.0
			return true
		default:
			return false
		}
	}

	return false
}

// typeName is t_haxe_generator::type_name.
func (g *generator) typeName(ttype sema.Type) string {
	ttype = sema.TrueType(ttype)

	if ttype.IsBaseType() {
		return g.baseTypeName(ttype.(*sema.BaseType))
	}

	if ttype.IsEnum() {
		return "Int"
	}

	if ttype.IsMap() {
		m := ttype.(*sema.Map)
		tkey := sema.TrueType(m.KeyType())
		tval := m.ValType()
		if tkey.IsBaseType() {
			switch tkey.(*sema.BaseType).Base() {
			case sema.TypeString:
				if !tkey.IsBinary() {
					return "StringMap< " + g.typeName(tval) + ">"
				}
				return "BytesMap< " + g.typeName(tval) + ">" // content equality, not reference equality
			case sema.TypeUUID:
				return "StringMap< " + g.typeName(tval) + ">" // uuids are stored as strings
			case sema.TypeBool:
				return "BoolMap< " + g.typeName(tval) + ">"
			case sema.TypeDouble:
				return "FloatMap< " + g.typeName(tval) + ">"
			case sema.TypeI8, sema.TypeI16, sema.TypeI32:
				return "IntMap< " + g.typeName(tval) + ">"
			case sema.TypeI64:
				return "Int64Map< " + g.typeName(tval) + ">"
			default:
				// default to ObjectMap<>
			}
		}
		if tkey.IsEnum() {
			return "IntMap< " + g.typeName(tval) + ">"
		}
		return "ObjectMap< " + g.typeName(tkey) + ", " + g.typeName(tval) + ">"
	}

	if ttype.IsSet() {
		s := ttype.(*sema.Set)
		tkey := sema.TrueType(s.ElemType())
		if tkey.IsBaseType() {
			switch tkey.(*sema.BaseType).Base() {
			case sema.TypeString:
				if !tkey.IsBinary() {
					return "StringSet"
				}
				return "BytesSet" // content equality, not reference equality
			case sema.TypeUUID:
				return "StringSet" // uuids are stored as strings
			case sema.TypeBool:
				return "BoolSet"
			case sema.TypeDouble:
				return "FloatSet"
			case sema.TypeI8, sema.TypeI16, sema.TypeI32:
				return "IntSet"
			case sema.TypeI64:
				return "Int64Set"
			default:
				// default to ObjectSet
			}
		}
		if tkey.IsEnum() {
			return "IntSet"
		}
		return "ObjectSet< " + g.typeName(tkey) + ">"
	}

	if ttype.IsList() {
		l := ttype.(*sema.List)
		return "List< " + g.typeName(l.ElemType()) + ">"
	}

	// Check for namespacing
	program := ttype.Program()
	if program != nil && program != g.program {
		pkg := makePackageName(program.Namespace("haxe"))
		if pkg != "" {
			return pkg + "." + g.makeHaxeUserTypeName(ttype.Name())
		}
	}

	return g.makeHaxeUserTypeName(ttype.Name())
}

// baseTypeName is t_haxe_generator::base_type_name.
func (g *generator) baseTypeName(t *sema.BaseType) string {
	switch t.Base() {
	case sema.TypeVoid:
		return "Void"
	case sema.TypeString:
		if t.IsBinary() {
			return "haxe.io.Bytes"
		}
		return "String"
	case sema.TypeUUID:
		return "String"
	case sema.TypeBool:
		return "Bool"
	case sema.TypeI8, sema.TypeI16, sema.TypeI32:
		return "haxe.Int32"
	case sema.TypeI64:
		return "haxe.Int64"
	case sema.TypeDouble:
		return "Float"
	default:
		emit.Throw("compiler error: no Haxe name for base type %s", sema.BaseName(t.Base()))
		return ""
	}
}

// typeToEnum is t_haxe_generator::type_to_enum.
func (g *generator) typeToEnum(t sema.Type) string {
	t = sema.TrueType(t)

	if t.IsBaseType() {
		switch t.(*sema.BaseType).Base() {
		case sema.TypeVoid:
			emit.Throw("NO T_VOID CONSTRUCT")
		case sema.TypeString:
			return "TType.STRING"
		case sema.TypeUUID:
			return "TType.UUID"
		case sema.TypeBool:
			return "TType.BOOL"
		case sema.TypeI8:
			return "TType.BYTE"
		case sema.TypeI16:
			return "TType.I16"
		case sema.TypeI32:
			return "TType.I32"
		case sema.TypeI64:
			return "TType.I64"
		case sema.TypeDouble:
			return "TType.DOUBLE"
		}
	} else if t.IsEnum() {
		return "TType.I32"
	} else if t.IsStruct() || t.IsXception() {
		return "TType.STRUCT"
	} else if t.IsMap() {
		return "TType.MAP"
	} else if t.IsSet() {
		return "TType.SET"
	} else if t.IsList() {
		return "TType.LIST"
	}

	emit.Throw("INVALID TYPE IN type_to_enum: %s", t.Name())
	return ""
}

// getHaxeTypeString is t_haxe_generator::get_haxe_type_string.
func (g *generator) getHaxeTypeString(t sema.Type) string {
	switch {
	case t.IsList():
		return "TType.LIST"
	case t.IsMap():
		return "TType.MAP"
	case t.IsSet():
		return "TType.SET"
	case t.IsStruct() || t.IsXception():
		return "TType.STRUCT"
	case t.IsEnum():
		return "TType.I32"
	case t.IsTypedef():
		return g.getHaxeTypeString(t.(*sema.Typedef).Type())
	case t.IsBaseType():
		switch t.(*sema.BaseType).Base() {
		case sema.TypeVoid:
			return "TType.VOID_"
		case sema.TypeString:
			return "TType.STRING"
		case sema.TypeUUID:
			return "TType.UUID"
		case sema.TypeBool:
			return "TType.BOOL"
		case sema.TypeI8:
			return "TType.BYTE"
		case sema.TypeI16:
			return "TType.I16"
		case sema.TypeI32:
			return "TType.I32"
		case sema.TypeI64:
			return "TType.I64"
		case sema.TypeDouble:
			return "TType.DOUBLE"
		default:
			emit.Throw("Unknown thrift type \"%s\" passed to t_haxe_generator::get_haxe_type_string!", t.Name())
		}
	default:
		emit.Throw("Unknown thrift type \"%s\" passed to t_haxe_generator::get_haxe_type_string!", t.Name())
	}
	return ""
}

// getEnumClassName is t_haxe_generator::get_enum_class_name (the override
// of t_oop_generator::get_enum_class_name).
func (g *generator) getEnumClassName(t sema.Type) string {
	pkg := ""
	program := t.Program()
	if program != nil {
		pkg = makePackageName(program.Namespace("haxe")) + "."
	}
	return pkg + t.Name()
}

// escapeHaxeKeyword is t_haxe_generator::escape_haxe_keyword: appends a
// "_" suffix to any Haxe language keyword used as an identifier,
// preserving the original name in wire-format string literals.
func escapeHaxeKeyword(name string) string {
	if haxeKeywords[name] {
		return name + "_"
	}
	return name
}

var haxeKeywords = map[string]bool{
	"abstract": true, "break": true, "case": true, "cast": true, "catch": true, "class": true, "continue": true, "default": true,
	"do": true, "dynamic": true, "else": true, "enum": true, "extends": true, "extern": true, "false": true, "final": true,
	"for": true, "function": true, "if": true, "implements": true, "import": true, "in": true, "inline": true, "interface": true,
	"macro": true, "new": true, "null": true, "operator": true, "overload": true, "override": true, "package": true,
	"private": true, "public": true, "return": true, "static": true, "switch": true, "this": true, "throw": true, "true": true,
	"try": true, "typedef": true, "untyped": true, "using": true, "var": true, "while": true,
}

// getCapName is t_haxe_generator::get_cap_name.
func getCapName(name string) string {
	if len(name) == 0 {
		return name
	}

	// test.for.Generic< data.Type, or.the.Like> and handle it recursively
	genericFirst := strings.IndexByte(name, '<')
	genericLast := strings.LastIndexByte(name, '>')
	if genericFirst >= 0 && genericLast >= 0 {
		outerType := name[:genericFirst]
		innerTypes := name[genericFirst+1 : genericLast]

		newInner := ""
		commaStart := 0
		for commaStart < len(innerTypes) {
			commaPos := commaStart
			nested := 0
			for commaPos < len(innerTypes) {
				found := false
				switch innerTypes[commaPos] {
				case '<':
					nested++
				case '>':
					nested--
				case ',':
					found = nested == 0
				}
				if found {
					break
				}
				commaPos++
			}

			if len(newInner) > 0 {
				newInner += ","
			}

			inner := innerTypes[commaStart:commaPos]
			newInner += getCapName(inner)
			commaStart = commaPos + 1
		}

		return getCapName(outerType) + "<" + newInner + ">"
	}

	b := []byte(name)

	// package name
	index := indexNotOf(b, " \n\r\t")
	if index >= 0 && index < len(b) {
		b[index] = toLowerByte(b[index])
		idx := indexByteFrom(b, '.', 0)
		for idx >= 0 {
			idx++
			if idx < len(b) {
				b[idx] = toLowerByte(b[idx])
			}
			idx = indexByteFrom(b, '.', idx)
		}
	}

	// class name
	var classIndex int
	if dot := lastIndexByte(b, '.'); dot >= 0 {
		classIndex = dot + 1
	} else {
		ni := indexNotOf(b, " \n\r\t")
		if ni < 0 {
			classIndex = len(b)
		} else {
			classIndex = ni
		}
	}

	if classIndex < len(b) {
		b[classIndex] = toUpperByte(b[classIndex])
	}

	name = string(b)

	// Avoid clashing with Haxe built-in and standard-library type names.
	// Only list names that are never returned by type_name() for Thrift
	// base types, so that base-type annotations (Bool, Int, Float, String,
	// Void) are unaffected.
	dot := strings.LastIndexByte(name, '.')
	lastComponent := name
	if dot >= 0 {
		lastComponent = name[dot+1:]
	}
	if haxeReservedTypes[lastComponent] {
		name += "_"
	}

	return name
}

var haxeReservedTypes = map[string]bool{
	"Array": true, "Class": true, "Date": true, "DateTools": true, "Dynamic": true, "Enum": true, "EnumValue": true, "EReg": true,
	"IntIterator": true, "Iterable": true, "Iterator": true, "KeyValueIterable": true, "KeyValueIterator": true,
	"Lambda": true, "Map": true, "Math": true, "Null": true, "Reflect": true, "Single": true, "Std": true, "StringBuf": true,
	"Sys": true, "Type": true, "UInt": true, "Xml": true,
}

// haxeBaseTypeNames is the HAXE_BASE_TYPE_NAMES set of
// t_haxe_generator::make_haxe_user_type_name.
var haxeBaseTypeNames = map[string]bool{
	"String": true, "Bool": true, "Float": true, "Int": true, "Void": true,
}

// makeHaxeUserTypeName is t_haxe_generator::make_haxe_user_type_name: like
// getCapName but also renames user-defined types whose capitalized name
// would shadow a Haxe base type (String, Bool, Float, Int, Void). Must NOT
// be used for base-type annotations — only for user-defined
// struct/enum/service identifiers (file names, class headers, imports).
func (g *generator) makeHaxeUserTypeName(name string) string {
	result := getCapName(name)
	dot := strings.LastIndexByte(result, '.')
	lastComponent := result
	if dot >= 0 {
		lastComponent = result[dot+1:]
	}
	if haxeBaseTypeNames[lastComponent] {
		result += "_"
	}
	return result
}

// constantName is t_haxe_generator::constant_name.
func constantName(name string) string {
	var sb strings.Builder
	isFirst := true
	wasPreviousCharUpper := false
	for i := 0; i < len(name); i++ {
		c := name[i]
		up := isUpper(c)
		if up && !isFirst && !wasPreviousCharUpper {
			sb.WriteByte('_')
		}
		sb.WriteByte(toUpperByte(c))
		isFirst = false
		wasPreviousCharUpper = up
	}
	return sb.String()
}

// indexNotOf returns the index of the first byte in b that is not in cutset,
// or -1, like std::string::find_first_not_of.
func indexNotOf(b []byte, cutset string) int {
	for i, c := range b {
		if strings.IndexByte(cutset, c) < 0 {
			return i
		}
	}
	return -1
}

func indexByteFrom(b []byte, c byte, from int) int {
	if from < 0 || from > len(b) {
		return -1
	}
	for i := from; i < len(b); i++ {
		if b[i] == c {
			return i
		}
	}
	return -1
}

func lastIndexByte(b []byte, c byte) int {
	for i := len(b) - 1; i >= 0; i-- {
		if b[i] == c {
			return i
		}
	}
	return -1
}

// generateRttiDecoration is t_haxe_generator::generate_rtti_decoration.
