// makeHaxeStringLiteral is t_haxe_generator::make_haxe_string_literal.
func makeHaxeStringLiteral(value string) string {
	if len(value) == 0 {
		return ""
	}

	var result strings.Builder
	result.WriteByte('"')
	for i := 0; i < len(value); i++ {
		c := value[i]
		switch {
		case c < 32:
			// convert ctrl chars, but leave UTF-8 alone; width = min(sizeof(signed char), 6) = 1
			result.WriteString("\\u{" + strconv.FormatInt(int64(c), 16) + "}")
		case c == '\\' || c == '"':
			result.WriteByte('\\')
			result.WriteByte(c)
		default:
			result.WriteByte(c)
		}
	}
	result.WriteByte('"')

	return result.String()
}

// generateDeprecationAttribute is t_haxe_generator::generate_deprecation_attribute.
func (g *generator) generateDeprecationAttribute(out *strings.Builder, fn *sema.Function, asComment bool) {
	values, ok := fn.Annotations()["deprecated"]
	if !ok {
		return
	}
	if asComment {
		out.WriteString(g.indent() + "// DEPRECATED")
	} else {
		out.WriteString(g.indent() + "@:deprecated")
	}

	// empty annotation values end up with "1" somewhere, ignore these as well
	last := ""
	if len(values) > 0 {
		last = values[len(values)-1]
	}
	if len(last) > 0 && last != "1" {
		text := makeHaxeStringLiteral(last)
		if asComment {
			out.WriteString(": " + text)
		} else {
			out.WriteString("(" + text + ")")
		}
	}

	out.WriteString("\n")
}
