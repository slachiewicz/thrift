// generateNewHashFromType is generate_new_hash_from_type. value may be
// nil, matching a nullptr argument in the C++ source.
func (g *Generator) generateNewHashFromType(key, value sema.Type) string {
	hashFunc := g.generateHashFuncFromType(key)
	cmpFunc := g.generateCmpFuncFromType(key)
	keyFreeFunc := g.generateFreeFuncFromType(key)
	valueFreeFunc := g.generateFreeFuncFromType(value)

	return "g_hash_table_new_full (" + hashFunc + ", " + cmpFunc + ", " + keyFreeFunc + ", " + valueFreeFunc + ");"
}

// generateNewArrayFromType is generate_new_array_from_type.
func (g *Generator) generateNewArrayFromType(ttype sema.Type) string {
	if ttype.IsVoid() {
		emit.Throw("compiler error: cannot determine array type")
	}
	if g.isNumeric(ttype) {
		return "g_array_new (0, 1, sizeof (" + g.baseTypeName(ttype) + "));"
	}
	freeFunc := g.generateFreeFuncFromType(ttype)
	return "g_ptr_array_new_with_free_func (" + freeFunc + ");"
}
