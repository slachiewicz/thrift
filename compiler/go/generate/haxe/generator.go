// outDir is t_generator::get_out_dir with out_dir_base_ == "gen-haxe".
func (g *generator) outDir() string {
	if g.program.IsOutPathAbsolute() {
		return g.program.OutPath() + "/"
	}
	return g.program.OutPath() + "gen-haxe" + "/"
}

// autogenComment is the base t_generator::autogen_comment (not overridden
// by t_haxe_generator).
func (g *generator) autogenComment() string {
	return "/**\n" +
		" * Autogenerated by Thrift Compiler (" + version.Version + ")\n" +
		" *\n" +
		" * DO NOT EDIT UNLESS YOU ARE SURE THAT YOU KNOW WHAT YOU ARE DOING\n" +
		" *  @generated\n" +
		" */\n"
}

// initGenerator is t_haxe_generator::init_generator.
func (g *generator) initGenerator() {
	emit.Mkdir(g.outDir())
	g.packageName = makePackageName(g.program.Namespace("haxe"))

	dir := g.packageName
	subdir := g.outDir()
	for {
		loc := strings.IndexByte(dir, '.')
		if loc < 0 {
			break
		}
		subdir = subdir + "/" + dir[:loc]
		emit.Mkdir(subdir)
		dir = dir[loc+1:]
	}
	if len(dir) > 0 {
		subdir = subdir + "/" + dir
		emit.Mkdir(subdir)
	}

	g.packageDir = subdir
}

// makePackageName is t_haxe_generator::make_package_name: Haxe package
// names start with lowercase letters.
func makePackageName(value string) string {
	if len(value) == 0 {
		return value
	}
	b := []byte(value)
	b[0] = toLowerByte(b[0])
	for i := 0; i < len(b); i++ {
		if b[i] == '.' && i+1 < len(b) {
			b[i+1] = toLowerByte(b[i+1])
		}
	}
	return string(b)
}

// haxePackage is t_haxe_generator::haxe_package.
func (g *generator) haxePackage() string {
	if g.packageName != "" {
		return "package " + g.packageName
	}
	return "package"
}

