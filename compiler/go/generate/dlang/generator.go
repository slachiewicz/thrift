// Options are the "d:" generator options. The C++ generator's constructor
// registers none ("/* no options yet */") and throws "unknown option
// d:<key>" for anything it is handed; see ParseOptions.
type Options struct{}

// ParseOptions parses the part after "d:" of a --gen argument.
func ParseOptions(spec string) (Options, error) {
	var o Options
	for _, option := range strings.Split(spec, ",") {
		if option == "" {
			continue
		}
		key := option
		if i := strings.IndexByte(option, '='); i >= 0 {
			key = option[:i]
		}
		return o, &emit.Error{Msg: "unknown option d:" + key}
	}
	return o, nil
}

// dfile is ofstream_with_content_based_conditional_update: a buffered
// output file, written out with emit.WriteFile once complete.
type dfile struct {
	sb strings.Builder
}

func (f *dfile) write(s string) { f.sb.WriteString(s) }
func (f *dfile) String() string { return f.sb.String() }

// cppNamed is t_container's has_cpp_name()/get_cpp_name(), reached
// through a type assertion since t_container is not surfaced as an
// interface in sema.
type cppNamed interface {
	HasCppName() bool
	CppName() string
}

// Generator is t_d_generator for one program.
type Generator struct {
	program     *sema.Program
	opts        Options
	programName string // program_name_
	packageDir  string // package_dir_
	indentLevel int    // t_generator's indent_

	fTypes dfile // f_types_
}

func newGenerator(program *sema.Program, opts Options) *Generator {
	return &Generator{program: program, opts: opts, programName: program.Name()}
}

// ---- t_generator/t_oop_generator helpers ----

func (g *Generator) indentUp()   { g.indentLevel++ }
func (g *Generator) indentDown() { g.indentLevel-- }

// indent is indent(): t_d_generator does not override indent_str(), so
// the t_generator default of two spaces per level applies.
func (g *Generator) indent() string {
	return strings.Repeat("  ", g.indentLevel)
}

// outDir is get_out_dir() with out_dir_base_ "gen-d".
func (g *Generator) outDir() string {
	if g.program.IsOutPathAbsolute() {
		return g.program.OutPath() + "/"
	}
	return g.program.OutPath() + "gen-d/"
}

func autogenSummary() string {
	return "Autogenerated by Thrift Compiler (" + version.Version + ")"
}

func autogenComment() string {
	return "/**\n" + " * " + autogenSummary() + "\n" + " *\n" +
		" * DO NOT EDIT UNLESS YOU ARE SURE THAT YOU KNOW WHAT YOU ARE DOING\n" +
		" *  @generated\n" + " */\n"
}

// formatDouble mimics `ostream << double` with the default precision of
// six significant digits: t_d_generator never calls
// emit_double_as_string, so the field just streams through operator<<.
func formatDouble(f float64) string {
	return strconv.FormatFloat(f, 'g', 6, 64)
}

